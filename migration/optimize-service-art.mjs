/**
 * Optimize raster service thumbnails.
 *
 * Drop source images into  public/services-art/source/  named after the
 * service slug, e.g.  agentic-ai-development.jpg  (or .png/.webp/.jpeg).
 * This resizes each to a 1200×750 cover crop, encodes efficient WebP,
 * writes  public/services-art/<slug>.webp , and regenerates the manifest
 * src/lib/service-art.ts so the pages switch that service from the
 * generated SVG to the photo automatically.
 *
 * Usage: npm run services:art          (or: node migration/optimize-service-art.mjs)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ART = path.join(__dirname, "..", "public", "services-art");
const SRC = path.join(ART, "source");
const MANIFEST = path.join(__dirname, "..", "src", "lib", "service-art.ts");

fs.mkdirSync(SRC, { recursive: true });

const exts = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);
const sources = fs
  .readdirSync(SRC)
  .filter((f) => exts.has(path.extname(f).toLowerCase()));

const done = [];
for (const file of sources) {
  const slug = path.basename(file, path.extname(file)).trim().toLowerCase();
  const out = path.join(ART, `${slug}.webp`);
  try {
    await sharp(path.join(SRC, file))
      .resize(1200, 750, { fit: "cover", position: "attention" })
      .webp({ quality: 78, effort: 5 })
      .toFile(out);
    const kb = (fs.statSync(out).size / 1024).toFixed(0);
    done.push(slug);
    console.log(`✓ ${slug}.webp (${kb} KB)`);
  } catch (e) {
    console.log(`✗ ${file}: ${e.message}`);
  }
}

done.sort();
const banner =
  "// AUTO-GENERATED by migration/optimize-service-art.mjs — do not edit by hand.\n" +
  "// Service slugs that have an optimized raster thumbnail in public/services-art/<slug>.webp.\n";
fs.writeFileSync(
  MANIFEST,
  `${banner}export const RASTER_SERVICE_ART = new Set<string>([\n${done
    .map((s) => `  ${JSON.stringify(s)},`)
    .join("\n")}\n]);\n\nexport function serviceArt(slug: string): string {\n  return RASTER_SERVICE_ART.has(slug)\n    ? \`/services-art/\${slug}.webp\`\n    : \`/services-art/\${slug}.svg\`;\n}\n`
);

console.log(
  `\noptimized ${done.length}/${sources.length} images; manifest → src/lib/service-art.ts`
);
if (sources.length === 0) {
  console.log(
    "\nNo source images found. Add files to public/services-art/source/ named\n" +
      "after each service slug (e.g. agentic-ai-development.jpg) and re-run."
  );
}
