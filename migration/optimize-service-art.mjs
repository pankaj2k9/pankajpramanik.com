/**
 * Optimize raster service thumbnails.
 *
 * Drop source images into  public/services-art/source/  named after the
 * service slug, e.g.  agentic-ai-development.jpg  (or .png/.webp/.jpeg).
 * This resizes each to a 1200×750 cover crop, encodes efficient WebP,
 * writes  public/services-art/<slug>.webp , and regenerates the manifest
 * src/lib/service-art.ts so the pages switch that service from the
 * generated SVG to the photo automatically.
 *
 * Usage: npm run services:art          (or: node migration/optimize-service-art.mjs)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ART = path.join(__dirname, "..", "public", "services-art");
const SRC = path.join(ART, "source");
const MANIFEST = path.join(__dirname, "..", "src", "lib", "service-art.ts");

fs.mkdirSync(SRC, { recursive: true });

// Files may be named after the service slug (e.g. agentic-ai-development.jpg)
// OR simply numbered 1..15 in the order the thumbnails were provided — this
// map assigns each number to its service by theme.
const ORDER_MAP = {
  1: "llm-rag-developer-hire", //            wireframe glowing brain + circuits
  2: "data-structure-and-algorithm-problem-solving", // abstract rainbow lines/particles
  3: "ai-based-software-development", //      brain + hand + code windows/flowchart
  4: "data-science-and-machine-learning", //  low-poly brain + data particles
  5: "hire-ai-langchain-expert", //           chains: LMs/Tools/Memory/Agents
  6: "deep-learning-solutions", //            neural net INPUT/HIDDEN/OUTPUT + sine
  7: "vector-database-integration-expert", // isometric DB servers + arrows
  8: "hire-data-analytics-visualization-expert", // dashboards + line charts
  9: "hire-the-perfect-mlops-developer", //   CI/CD infinity + neural + containers
  10: "chatting-app-development", //           chat bubbles + user network
  11: "hire-cloud-devops-engineer-ai", //      glass cloud + glowing cubes
  12: "hire-ai-data-pipeline-engineer", //     green particle brain → pipes/ports
  13: "ai-voice-assistant-developer", //       microphone + soundwave → brain
  14: "ai-chatbot-agent-designer", //          neon circuit brain + chat + hex icons
  15: "agentic-ai-development", //             circuit brain + chat + diamond bursts
};

const exts = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);
const sources = fs
  .readdirSync(SRC)
  .filter((f) => exts.has(path.extname(f).toLowerCase()));

const done = [];
for (const file of sources) {
  const base = path.basename(file, path.extname(file)).trim().toLowerCase();
  const num = base.match(/^0*(\d{1,2})$/);
  const slug = num ? ORDER_MAP[Number(num[1])] : base;
  if (!slug) {
    console.log(`✗ ${file}: no mapping for "${base}" (name it after a service slug)`);
    continue;
  }
  const out = path.join(ART, `${slug}.webp`);
  try {
    await sharp(path.join(SRC, file))
      .resize(1200, 750, { fit: "cover", position: "attention" })
      .webp({ quality: 78, effort: 5 })
      .toFile(out);
    const kb = (fs.statSync(out).size / 1024).toFixed(0);
    done.push(slug);
    console.log(`✓ ${slug}.webp (${kb} KB)`);
  } catch (e) {
    console.log(`✗ ${file}: ${e.message}`);
  }
}

done.sort();
const banner =
  "// AUTO-GENERATED by migration/optimize-service-art.mjs — do not edit by hand.\n" +
  "// Service slugs that have an optimized raster thumbnail in public/services-art/<slug>.webp.\n";
fs.writeFileSync(
  MANIFEST,
  `${banner}export const RASTER_SERVICE_ART = new Set<string>([\n${done
    .map((s) => `  ${JSON.stringify(s)},`)
    .join("\n")}\n]);\n\nexport function serviceArt(slug: string): string {\n  return RASTER_SERVICE_ART.has(slug)\n    ? \`/services-art/\${slug}.webp\`\n    : \`/services-art/\${slug}.svg\`;\n}\n`
);

console.log(
  `\noptimized ${done.length}/${sources.length} images; manifest → src/lib/service-art.ts`
);
if (sources.length === 0) {
  console.log(
    "\nNo source images found. Add files to public/services-art/source/ named\n" +
      "after each service slug (e.g. agentic-ai-development.jpg) and re-run."
  );
}
